const assert = require('node:assert/strict');
const fs = require('node:fs');
const esbuild = require('esbuild');
const vm = require('node:vm');
const {code} = esbuild.transformSync(fs.readFileSync('convex/lib/enrichment.ts','utf8'),{loader:'ts',format:'cjs'});
const context={module:{exports:{}},URL};
vm.runInNewContext(code,context);
const {mayStart,createSearchRequest,validateFacts,safeSourceUrl,pageText}=context.module.exports;
assert.equal(mayStart(undefined,false),true);
for(const status of ['running','completed','failed'])assert.equal(mayStart({status,attempts:1},false),false);
assert.equal(mayStart({status:'running',attempts:1},true),false);
assert.equal(mayStart({status:'completed',attempts:1},true),true);
assert.equal(mayStart({status:'failed',attempts:1},true),true);
const request=createSearchRequest('Example Manufacturing');
assert.equal(request.model,'gpt-6-luna');
assert.equal(request.max_tool_calls,1);
assert.equal(request.max_output_tokens,1200);
assert.equal(request.tool_choice,'required');
assert.equal(request.store,false);
assert.deepEqual(JSON.parse(request.input),{company:'Example Manufacturing'});
for(const url of ['http://example.com','https://127.0.0.1','https://localhost','https://[::1]','https://user:password@example.com','https://example.com:8080'])assert.equal(safeSourceUrl(url),null);
const url='https://example.com/annual-report';
const sources=new Set([url]);
const pages=new Map([[url,pageText('<p>Annual turnover was USD 10 million in 2025.</p><p>Our industry is furniture manufacturing.</p><p>We faced rising raw material costs this year.</p>')]]);
const fact=(value,evidence,sourceUrl=url)=>({value,evidence,sourceUrl});
const input={revenueBand:fact('USD 10 million','Annual turnover was USD 10 million in 2025.'),industry:fact('furniture manufacturing','Our industry is furniture manufacturing.'),companyProblems:[fact('rising raw material costs','We faced rising raw material costs this year.')]};
let result=validateFacts(input,sources,pages);
assert.equal(result.revenueBand.value,'USD 10 million');
assert.equal(result.industry.sourceUrl,url);
assert.equal(result.companyProblems.length,1);
result=validateFacts({...input,revenueBand:fact('USD 50 million',input.revenueBand.evidence)},sources,pages);
assert.equal(result.revenueBand.value,'not found');
const operatingIncome='The company reported operating income of Rs 20 crore in fiscal 2025';
result=validateFacts({...input,revenueBand:fact('Rs 20 crore in fiscal 2025',operatingIncome)},sources,new Map([[url,pageText(operatingIncome)]]));
assert.equal(result.revenueBand.value,'Rs 20 crore in fiscal 2025');
result=validateFacts({...input,industry:fact('furniture manufacturing',input.industry.evidence,'https://example.com/unsearched')},sources,pages);
assert.equal(result.industry.value,'not found');
result=validateFacts(input,sources,new Map());
assert.equal(result.revenueBand.value,'not found');
assert.equal(result.industry.value,'not found');
assert.equal(result.companyProblems.length,0);
const estimate='Estimated annual revenue was USD 10 million.';
result=validateFacts({...input,revenueBand:fact('USD 10 million',estimate)},sources,new Map([[url,pageText(estimate)]]));
assert.equal(result.revenueBand.value,'not found');
result=validateFacts({revenueBand:null,industry:{value:'not found',sourceUrl:null,evidence:''},companyProblems:[]},sources,pages);
assert.equal(result.industry.sourceUrl,null);
console.log('Enrichment safeguards passed: repeat runs, privacy, one-call cap, exact evidence, unavailable pages, unsearched sources and invented/estimated revenue.');

const normalized=context.module.exports.normalizeText('Our manu-\nfacturing revenue was Rs 10 million.');
assert.equal(normalized,'our manufacturing revenue was rs 10 million.');
assert.match(createSearchRequest('Example India',false).instructions,/no global parent revenue fallback/);
assert.match(createSearchRequest('Example India',true).instructions,/revenueScope to global group/);

const tableEvidence='in rs crores fy13 fy23 10y cagr revenues 4,225 16,868 15%';
assert.equal(validateFacts({revenueBand:fact('16,868',tableEvidence)},sources,new Map([[url,pageText(tableEvidence)]])).revenueBand.value,'16,868');

const riskRequest=context.module.exports.createRiskSearchRequest('Example India');
assert.equal(riskRequest.max_tool_calls,1);
assert.match(riskRequest.instructions,/latest publicly available annual report/);
assert.match(riskRequest.instructions,/Never include personal names, contacts, revenue or industry/);
const risks=context.module.exports.validateRisks({companyProblems:[fact('Material costs could rise','We faced rising raw material costs this year.')]},sources,pages);
assert.equal(risks.length,1);
assert.equal(context.module.exports.validateRisks({companyProblems:[fact('Material costs could rise','A completely invented evidence passage.') ]},sources,pages).length,0);
